#!/usr/bin/env python3
"""Write backend/src/LibCompiler/LibCompiler.fsproj from upstream's DarkCompiler.fsproj.

Same compile list and order, minus Program.fs; a Library, not an Exe; upstream's
default warning posture instead of the backend's --warnaserror set; and the .dark
stdlib and unicode tables copied next to the dll, which is where the compiler's
loader looks first.
"""
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
text = open(src).read()
compiles = [m for m in re.findall(r'<Compile Include="([^"]+)" />', text) if m != "Program.fs"]
items = "\n".join(f'    <Compile Include="{c}" />' for c in compiles)
open(dst, "w").write(f'''<Project Sdk="Microsoft.NET.Sdk">

  <!--
    GENERATED by scripts/build/_gen-libcompiler-fsproj.py from upstream's
    DarkCompiler.fsproj at the commit in vendor/VENDORED-FROM. Do not edit; re-vendor.

    LibCompiler is darklang-compiler (pbiggar/darklang-compiler) as a build-gated
    library: not part of the default build, referenced only under
    -p:DarkWithCompiler=true. The standalone Program.fs is dropped; everything else
    is upstream's, in upstream's order.
  -->
  <PropertyGroup>
    <OutputType>Library</OutputType>
    <IsPublishable>false</IsPublishable>
    <IsTrimmable>false</IsTrimmable>
    <!-- Vendored code builds under its own warning posture, not the backend's. -->
    <OtherFlags>--test:GraphBasedChecking --test:ParallelOptimization --test:ParallelIlxGen --nowarn:1182,3387,3366,25,20,64,40</OtherFlags>
    <TreatWarningsAsErrors>false</TreatWarningsAsErrors>
    <NoWarn>NU1900</NoWarn>
    <WarningLevel>0</WarningLevel>
  </PropertyGroup>

  <ItemGroup>
{items}
  </ItemGroup>

  <ItemGroup>
    <!-- The compiler reads its stdlib from files next to the assembly. -->
    <Content Include="stdlib/**/*.dark">
      <CopyToOutputDirectory>PreserveNewest</CopyToOutputDirectory>
      <Link>stdlib/%(RecursiveDir)%(Filename)%(Extension)</Link>
    </Content>
    <Content Include="unicode_data.dark">
      <CopyToOutputDirectory>PreserveNewest</CopyToOutputDirectory>
    </Content>
    <Content Include="unicode_data/**/*.dark">
      <CopyToOutputDirectory>PreserveNewest</CopyToOutputDirectory>
      <Link>unicode_data/%(RecursiveDir)%(Filename)%(Extension)</Link>
    </Content>
    <Content Include="unicode_data_index/**/*.dark">
      <CopyToOutputDirectory>PreserveNewest</CopyToOutputDirectory>
      <Link>unicode_data_index/%(RecursiveDir)%(Filename)%(Extension)</Link>
    </Content>
  </ItemGroup>

</Project>
''')
print(f"{len(compiles)} compile items")
